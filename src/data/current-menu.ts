// Current printed menus supplied in October 2026. A row is name|price|portion.
function section(id: string, title: string, rows: string, intro = ""): MenuSection {
  const items: MenuItem[] = rows.trim().split("\n").map((line) => {
    const [name, price, weight = ""] = line.trim().split("|");
    return { name, price: `${price} ₽`, weight, description: "" };
  });
  return { id, title, intro, items };
}

